#define PG(nm, arr) { nm, arr, (int)(sizeof(arr)/sizeof(arr[0])) }
static const ParticleGroup k_particleGroups[] = {
    PG("Weapon unusuals", k_partWeapon),
    PG("Basic / community", k_partOther),
    PG("Cosmetic unusuals", k_partCosmetic),
    PG("Taunt unusuals",  k_partTaunt),
};
#undef PG
static constexpr int k_particleGroupCount = (int)(sizeof(k_particleGroups)/sizeof(k_particleGroups[0]));

// Display name for a stored SkinCfg::unusual value. 0 is a real id here, so
// "not set" is -1 in the UI and 0 in the cfg only when the user picked Invalid Particle.
inline const char* Particle_Name(int id)
{
    for (int g = 0; g < k_particleGroupCount; ++g)
        for (int i = 0; i < k_particleGroups[g].count; ++i)
            if (k_particleGroups[g].items[i].id == id) return k_particleGroups[g].items[i].name;
    return "(custom)";
}

