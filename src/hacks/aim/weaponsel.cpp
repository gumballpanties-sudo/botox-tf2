    // ---- css timing ------------------------------------------------------------------------
    // cubic-bezier(x1, y1, x2, y2) at progress p (newton on x, then y)
    float Bezier(float x1, float y1, float x2, float y2, float p)
    {
        if (p <= 0.f) return 0.f;
        if (p >= 1.f) return 1.f;
        float t = p;
        for (int i = 0; i < 8; i++)
        {
            const float x  = 3.f * (1.f - t) * (1.f - t) * t * x1 + 3.f * (1.f - t) * t * t * x2 + t * t * t;
            const float dx = 3.f * (1.f - t) * (1.f - t) * x1 + 6.f * (1.f - t) * t * (x2 - x1) + 3.f * t * t * (1.f - x2);
            if (fabsf(dx) < 1e-5f) break;
            t = std::clamp(t - (x - p) / dx, 0.f, 1.f);
        }
        return 3.f * (1.f - t) * (1.f - t) * t * y1 + 3.f * (1.f - t) * t * t * y2 + t * t * t;
    }

    // a css transition: eases from wherever it was to the new target
    struct Trans
    {
        float from = 0.f, to = 0.f, t0 = 0.f, dur = 0.f;
        bool  easeInOut = false;   // ease-in-out = cubic-bezier(.42, 0, .58, 1), else linear

        float Get(float now) const
        {
            if (dur <= 0.f) return to;
            const float p = (now - t0) / dur;
            return from + (to - from) * (easeInOut ? Bezier(0.42f, 0.f, 0.58f, 1.f, p) : std::clamp(p, 0.f, 1.f));
        }
        void Set(float target, float now, float d, bool anim)
        {
            if (target == to) return;
            from = anim ? Get(now) : target;
            to = target; t0 = now; dur = anim ? d : 0.f;
        }
        void Snap(float v) { from = to = v; dur = 0.f; }
    };

    // the --on-active keyframes (0-49% rest, 50% opacity .5 brightness 4 scale 1.1, 99% opacity .5
    // brightness 2 scale 1, 100% rest), 8 rounds from when the class went on
    struct Blink { float opacity = 1.f, bright = 1.f, scale = 1.f; };
    Blink BlinkAt(float t)
    {
        if (t < 0.f || t >= kBlinkPeriod * kBlinkCount) return {};
        const float p = fmodf(t, kBlinkPeriod) / kBlinkPeriod;
        auto lerp = [](float a, float b, float u) { return a + (b - a) * u; };
        if (p < 0.49f) return {};
        if (p < 0.5f)  { const float u = (p - 0.49f) / 0.01f; return { lerp(1.f, 0.5f, u), lerp(1.f, 4.f, u), lerp(1.f, 1.1f, u) }; }
        if (p < 0.99f) { const float u = (p - 0.5f) / 0.49f;  return { 0.5f, lerp(4.f, 2.f, u), lerp(1.1f, 1.f, u) }; }
        const float u = (p - 0.99f) / 0.01f;
        return { lerp(0.5f, 1.f, u), lerp(2.f, 1.f, u), 1.f };
    }

    // ---- colour ----------------------------------------------------------------------------
    float ToLinear(float c) { return c <= 0.04045f ? c / 12.92f : powf((c + 0.055f) / 1.055f, 2.4f); }
    float ToGamma(float c)  { return c <= 0.0031308f ? c * 12.92f : 1.055f * powf(c, 1.f / 2.4f) - 0.055f; }

    // csshelpers.cpp hsv-transform( c, 0, sat, val ): done in linear space
    void HsvTransform(const float in[3], float sat, float val, float out[3])
    {
        float l[3] = { ToLinear(in[0]), ToLinear(in[1]), ToLinear(in[2]) };
        const float mx = (std::max)({ l[0], l[1], l[2] }), mn = (std::min)({ l[0], l[1], l[2] });
        const float v = mx, s = mx > 0.f ? (mx - mn) / mx : 0.f;
        const float s2 = (std::min)(s * sat, 1.f), v2 = (std::min)(v * val, 1.f);
        for (int i = 0; i < 3; i++)   // hue kept: each channel keeps its place between min and max
        {
            const float f = (mx - mn) > 0.f ? (mx - l[i]) / (mx - mn) : 0.f;   // 0 at max, 1 at min
            out[i] = ToGamma(v2 * (1.f - s2 * f));
        }
    }

