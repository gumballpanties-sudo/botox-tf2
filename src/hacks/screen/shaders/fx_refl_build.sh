#!/usr/bin/env bash
# Rebuilds fx_refl.h (botox reflections.cpp: 5 ps_3_0 passes) from fx_refl.hlsl.
# Run from the project root (the dir holding src/):  bash src/hacks/screen/shaders/fx_refl_build.sh
# FXC=... overrides the compiler; otherwise the newest Windows Kits fxc is used. Fails if any pass > 512 slots.
set -euo pipefail

if [ -z "${FXC:-}" ]; then
    FXC=$(ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/fxc.exe 2>/dev/null | sort -V | tail -1)
fi
[ -x "$FXC" ] || { echo "fxc not found, set FXC="; exit 1; }

DIR=src/hacks/screen/shaders
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

OUT="$TMP/refl.h"
{
    echo "// GENERATED by fx_refl_build.sh from fx_refl.hlsl -- do not edit."
    echo "#pragma once"
} > "$OUT"

n=0
for name in k_fxReflNormals k_fxReflSmooth k_fxReflTrace k_fxReflFilter k_fxReflComposite; do
    "$FXC" //nologo //T ps_3_0 //E main //D PASS=$n //Fh "$TMP/v.h" //Fc "$TMP/v.asm" //Vn "$name" \
        "$DIR/fx_refl.hlsl" >/dev/null || { echo "$name failed"; exit 1; }
    slots=$(grep -o "approximately [0-9]*" "$TMP/v.asm" | grep -o "[0-9]*")
    [ "$slots" -le 512 ] || { echo "$name uses $slots slots (> 512)"; exit 1; }
    echo "$name: $slots slots"
    cat "$TMP/v.h" >> "$OUT"
    n=$((n + 1))
done

cp "$OUT" "$DIR/fx_refl.h"
echo "wrote $DIR/fx_refl.h"
