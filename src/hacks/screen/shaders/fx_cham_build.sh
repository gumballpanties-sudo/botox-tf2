#!/usr/bin/env bash
# Rebuilds the chams family vertex shaders (fx_cham_vs.h, fx_lsd_vs.h, fx_twotone_vs.h: one table each,
# [SKINNED][layout]) and fx_cham_ps.h (one ps_3_0 per shader chams mode).
# Run from the project root (the dir holding src/):  bash src/hacks/screen/shaders/fx_cham_build.sh
# FXC=... overrides the compiler; otherwise the newest Windows Kits fxc is used.
set -euo pipefail

COUNT=25                            # ChamsLayers::Count (chams_layers.h)
SKIP=" 0 12 13 "                    # original / lsd / two tone: not shader chams modes

if [ -z "${FXC:-}" ]; then
    FXC=$(ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/fxc.exe 2>/dev/null | sort -V | tail -1)
fi
[ -x "$FXC" ] || { echo "fxc not found, set FXC="; exit 1; }

DIR=src/hacks/screen/shaders
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# vs <hlsl> <out header> <table name> <layout defines...>
#   ->  static const FxVs <table>[2][2][N], indexed [DX8 (bones at c48 instead of c58)][SKINNED][layout]
# Each layout string is the extra /D list for that column (lsd_chams.cpp indexes columns by what the decl carries).
vs() {
    local src=$1 out=$2 name=$3; shift 3
    local layouts=("$@") n=${#layouts[@]}
    local hdr="$TMP/$name.h"
    {
        echo "// GENERATED by fx_cham_build.sh from $(basename "$src") -- do not edit."
        echo "#pragma once"
    } > "$hdr"
    for d in 0 1; do
        for s in 0 1; do
            for ((l = 0; l < n; l++)); do
                # shellcheck disable=SC2086
                "$FXC" //nologo //T vs_3_0 //E main //D DX8=$d //D SKINNED=$s ${layouts[$l]} //Fh "$TMP/${name}_${d}_${s}_${l}.h" //Vn ${name}_${d}_${s}_${l} "$src" >/dev/null \
                    || { echo "$name dx8=$d skinned=$s layout=$l failed"; exit 1; }
                cat "$TMP/${name}_${d}_${s}_${l}.h" >> "$hdr"
            done
        done
    done
    {
        echo ""
        echo "#ifndef FXVS_DEFINED"
        echo "#define FXVS_DEFINED"
        echo "struct FxVs { const BYTE* bytes; unsigned size; };"
        echo "#endif"
        echo "static const FxVs $name[2][2][$n] = {"
        for d in 0 1; do
            echo "    {"
            for s in 0 1; do
                printf "        { "
                for ((l = 0; l < n; l++)); do printf "{ %s_%d_%d_%d, sizeof(%s_%d_%d_%d) }, " "$name" $d $s $l "$name" $d $s $l; done
                echo "},"
            done
            echo "    },"
        done
        echo "};"
    } >> "$hdr"
    mv "$hdr" "$out"
}

# columns: 0 float verts, 1 compressed (UBYTE4 normal, SHORT2 weights)
vs "$DIR/fx_cham_vs.hlsl" "$DIR/fx_cham_vs.h" k_fxChamVs "//D COMPRESSED_VERTS=0" "//D COMPRESSED_VERTS=1"
vs "$DIR/fx_lsd_vs.hlsl"  "$DIR/fx_lsd_vs.h"  k_fxLsdVs  "//D COMPRESSED_VERTS=0" "//D COMPRESSED_VERTS=1"
# columns: 0 float verts, 1 float verts + TANGENT stream, 2 compressed (tangent packed in the normal)
vs "$DIR/fx_twotone_vs.hlsl" "$DIR/fx_twotone_vs.h" k_fxTwoToneVs \
    "//D COMPRESSED_VERTS=0 //D HAS_TANGENT=0" "//D COMPRESSED_VERTS=0 //D HAS_TANGENT=1" "//D COMPRESSED_VERTS=1 //D HAS_TANGENT=0"

OUT="$TMP/ps.h"
{
    echo "// GENERATED by fx_cham_build.sh from fx_cham_ps.hlsl -- do not edit."
    echo "#pragma once"
} > "$OUT"
for ((m = 0; m < COUNT; m++)); do
    [[ "$SKIP" == *" $m "* ]] && continue
    "$FXC" //nologo //T ps_3_0 //E main //D MODE=$m //Fh "$TMP/m$m.h" //Vn k_fxChamPs$m "$DIR/fx_cham_ps.hlsl" >/dev/null \
        || { echo "mode $m failed"; exit 1; }
    cat "$TMP/m$m.h" >> "$OUT"
done
{
    echo ""
    echo "struct FxChamPs { const BYTE* bytes; unsigned size; };"
    echo "static const FxChamPs k_fxChamPs[$COUNT] = {"
    for ((m = 0; m < COUNT; m++)); do
        if [[ "$SKIP" == *" $m "* ]]; then echo "    { nullptr, 0 },"; else echo "    { k_fxChamPs$m, sizeof(k_fxChamPs$m) },"; fi
    done
    echo "};"
} >> "$OUT"
mv "$OUT" "$DIR/fx_cham_ps.h"
echo "built cham/lsd/twotone vs tables, ps modes 0..$((COUNT - 1)) minus$SKIP"
