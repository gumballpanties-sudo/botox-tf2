#!/usr/bin/env bash
# Rebuilds fx_cham_vs.h (float + compressed verts) and fx_cham_ps.h (one ps_3_0 per shader chams mode).
# Run from the project root (the dir holding src/):  bash src/hacks/screen/shaders/fx_cham_build.sh
# FXC=... overrides the compiler; otherwise the newest Windows Kits fxc is used.
set -euo pipefail

COUNT=25                            # ChamsLayers::Count (chams_layers.h)
SKIP=" 0 12 13 "                    # original / lsd / two tone: not shader chams modes

if [ -z "${FXC:-}" ]; then
    FXC=$(ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/fxc.exe 2>/dev/null | sort -V | tail -1)
fi
[ -x "$FXC" ] || { echo "fxc not found, set FXC="; exit 1; }

DIR=src/hacks/screen/shaders
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

OUT="$TMP/vs.h"
{
    echo "// GENERATED by fx_cham_build.sh from fx_cham_vs.hlsl -- do not edit."
    echo "#pragma once"
} > "$OUT"
for c in 0 1; do
    "$FXC" //nologo //T vs_3_0 //E main //D COMPRESSED_VERTS=$c //Fh "$TMP/v$c.h" //Vn k_fxChamVs$c "$DIR/fx_cham_vs.hlsl" >/dev/null \
        || { echo "vs $c failed"; exit 1; }
    cat "$TMP/v$c.h" >> "$OUT"
done
mv "$OUT" "$DIR/fx_cham_vs.h"

OUT="$TMP/ps.h"
{
    echo "// GENERATED by fx_cham_build.sh from fx_cham_ps.hlsl -- do not edit."
    echo "#pragma once"
} > "$OUT"
for ((m = 0; m < COUNT; m++)); do
    [[ "$SKIP" == *" $m "* ]] && continue
    "$FXC" //nologo //T ps_3_0 //E main //D MODE=$m //Fh "$TMP/m$m.h" //Vn k_fxChamPs$m "$DIR/fx_cham_ps.hlsl" >/dev/null \
        || { echo "mode $m failed"; exit 1; }
    cat "$TMP/m$m.h" >> "$OUT"
done
{
    echo ""
    echo "struct FxChamPs { const BYTE* bytes; unsigned size; };"
    echo "static const FxChamPs k_fxChamPs[$COUNT] = {"
    for ((m = 0; m < COUNT; m++)); do
        if [[ "$SKIP" == *" $m "* ]]; then echo "    { nullptr, 0 },"; else echo "    { k_fxChamPs$m, sizeof(k_fxChamPs$m) },"; fi
    done
    echo "};"
} >> "$OUT"
mv "$OUT" "$DIR/fx_cham_ps.h"
echo "built vs x2, ps modes 0..$((COUNT - 1)) minus$SKIP"
