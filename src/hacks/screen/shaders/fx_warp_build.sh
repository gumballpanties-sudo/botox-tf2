#!/usr/bin/env bash
# Rebuilds fx_warp.h (one ps_3_0 per effect x blend group + the 2 slit scan history writers) from fx_warp.hlsl.
# Run from the project root (the dir holding src/):  bash src/hacks/screen/shaders/fx_warp_build.sh
# FXC=... overrides the compiler; otherwise the newest Windows Kits fxc is used. Fails if any variant > 512 slots.
set -euo pipefail

if [ -z "${FXC:-}" ]; then
    FXC=$(ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/fxc.exe 2>/dev/null | sort -V | tail -1)
fi
[ -x "$FXC" ] || { echo "fxc not found, set FXC="; exit 1; }

DIR=src/hacks/screen/shaders
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

OUT="$TMP/warp.h"
{
    echo "// GENERATED by fx_warp_build.sh from fx_warp.hlsl -- do not edit."
    echo "#pragma once"
} > "$OUT"

build() {   # name effect write blend
    "$FXC" //nologo //T ps_3_0 //E main //D EFFECT=$2 //D WRITE=$3 //D BLEND=$4 //Fh "$TMP/v.h" //Fc "$TMP/v.asm" //Vn "$1" \
        "$DIR/fx_warp.hlsl" >/dev/null || { echo "$1 failed"; exit 1; }
    local n
    n=$(grep -o "approximately [0-9]*" "$TMP/v.asm" | grep -o "[0-9]*")
    [ "$n" -le 512 ] || { echo "$1 uses $n slots (> 512)"; exit 1; }
    cat "$TMP/v.h" >> "$OUT"
}

for ((e = 0; e <= 10; e++)); do
    for ((b = 0; b <= 3; b++)); do
        [ $e -eq 0 ] && [ $b -ne 0 ] && continue
        build "k_fxWarpPs${e}_${b}" $e 0 $b
    done
done
build k_fxWarpWrite9 9 1 0
build k_fxWarpWrite10 10 1 0

{
    echo ""
    echo "struct FxWarpPs { const BYTE* bytes; unsigned size; };"
    echo "static const FxWarpPs k_fxWarpPs[11][4] = {"
    for ((e = 0; e <= 10; e++)); do
        line="    {"
        for ((b = 0; b <= 3; b++)); do
            n="k_fxWarpPs${e}_${b}"
            [ $e -eq 0 ] && n="k_fxWarpPs0_0"
            line="$line { $n, sizeof($n) },"
        done
        echo "$line },"
    done
    echo "};"
    echo "static const FxWarpPs k_fxWarpWrite[2] = { { k_fxWarpWrite9, sizeof(k_fxWarpWrite9) }, { k_fxWarpWrite10, sizeof(k_fxWarpWrite10) } };"
} >> "$OUT"
mv "$OUT" "$DIR/fx_warp.h"
echo "built fx_warp.h"
